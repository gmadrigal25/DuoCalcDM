"""Generates the us/, uk/ and eu/ version folders from the main index.html.

Each folder holds a copy of index.html that loads the shared app files from the folder above,
plus its own manifest, so each address installs as its own Home Screen app. The app reads the
folder name to pick the number format (see VERSIONS in app.js).

Run after changing index.html or manifest.webmanifest:
    python3 tools/make_versions.py           # write the folders
    python3 tools/make_versions.py --check   # fail if they're out of date (used by npm test)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
VERSIONS = {"us": "en-US", "uk": "en-GB", "eu": "en"}
SHARED = ["icon.png", "style.css", "engine.js", "app.js"]


def page(lang):
    html = (ROOT / "index.html").read_text()
    html = html.replace('<html lang="en">', '<html lang="%s">' % lang, 1)
    for name in SHARED:
        html = html.replace('href="%s"' % name, 'href="../%s"' % name)
        html = html.replace('src="%s"' % name, 'src="../%s"' % name)
    note = "<!-- Generated by tools/make_versions.py from ../index.html. Don't edit by hand. -->\n"
    return html.replace("<!doctype html>\n", "<!doctype html>\n" + note, 1)


def manifest():
    m = json.loads((ROOT / "manifest.webmanifest").read_text())
    m["start_url"] = "./"
    m["scope"] = "./"
    for icon in m.get("icons", []):
        icon["src"] = "../" + icon["src"]
    return json.dumps(m, indent=2, ensure_ascii=False) + "\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for folder, lang in VERSIONS.items():
        for name, text in (("index.html", page(lang)), ("manifest.webmanifest", manifest())):
            path = ROOT / folder / name
            if check:
                if not path.exists() or path.read_text() != text:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(exist_ok=True)
                path.write_text(text)
    if check and stale:
        print("Out of date, run python3 tools/make_versions.py:", ", ".join(stale))
        sys.exit(1)
    print("version folders " + ("up to date" if check else "written") + ": " + ", ".join(VERSIONS))


if __name__ == "__main__":
    main()
